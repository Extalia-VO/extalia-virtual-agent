/**
 * The mock serves the daemon's result shapes (`daemonKnowledge.ts`), as the real host forwards them.
 * `now`: the clock modification times count back from (tests pass a fixed one).
 */
export function createMockKnowledge(mode: MockKnowledgeMode, latency: () => Promise<void>, now: number = Date.now(), editOptions: MockKnowledgeEditOptions = {}): Pick<Required<AgentHostApi>, Methods> {
  // Edits replace or add notes (`mockKnowledgeEdit.ts`), so the list is this mock's own copy.
  let samples: readonly SampleNote[] = [...(mode === 'large' ? MOCK_LARGE_VAULT_NOTES : mode === 'sample' ? SAMPLE : [])];
  let generation = mode === 'empty' ? 0 : 7;
  let notes = index(samples, new Date(now - 6 * 60_000).toISOString(), now);
  // Links depend only on the indexed notes, and resolving all of them is the slow part: keep the last result.
  let linkCache: { notes: Indexed[]; links: KnowledgeLink[] } | undefined;
  const linksOf = (item: Indexed): KnowledgeLink[] => {
    const fmLines = 2 + [item.node.idFromFrontMatter, item.node.kind !== 'note', item.node.declaredVerification].filter(Boolean).length;
    return extractLinks(item.body, fmLines + 1).map((link, ordinal) => ({
      sourceNodeId: item.node.nodeId, ordinal, edgeType: link.edgeType, embed: link.embed, line: link.line, target: link.target,
      ...(link.heading ? { heading: link.heading } : {}), ...(link.display ? { display: link.display } : {}),
      ...resolve(notes, item.node.path, link.target),
    }));
  };
  const allLinks = (): KnowledgeLink[] => {
    if (linkCache?.notes !== notes) linkCache = { notes, links: notes.flatMap(linksOf) };
    return linkCache.links;
  };
  const unresolved = () => allLinks().filter(link => link.status !== 'resolved').length;
  const skipped: KnowledgeSkippedFile[] = mode !== 'empty' ? SAMPLE_SKIPPED : [];
  const summaryOf = (report: KnowledgeSyncReport): KnowledgeSyncSummary => ({
    mode: report.mode, at: report.at, generation: report.generation, notes: report.notes, added: report.added, updated: report.updated, removed: report.removed,
    unchanged: report.unchanged, renamed: report.renamedTotal, skipped: report.skippedTotal, unresolvedLinks: report.unresolvedLinks,
  });
  const report = (syncMode: KnowledgeSyncReport['mode'], at: string): KnowledgeSyncReport => ({
    mode: syncMode, at, generation, notes: notes.length, added: syncMode === 'rebuild' ? notes.length : 0, updated: 0, removed: 0,
    unchanged: syncMode === 'rebuild' ? 0 : notes.length, unresolvedLinks: unresolved(), renamed: [], renamedTotal: 0,
    skipped: skipped.map(item => ({ ...item })), skippedTotal: skipped.length, vaultCreated: false,
  });
  let lastSync: KnowledgeSyncReport | undefined = mode !== 'empty' ? report('incremental', new Date(now - 6 * 60_000).toISOString()) : undefined;
  const status = (): KnowledgeStatus => ({
    state: 'ready', vaultRoot: 'vaults/default', vaultPresent: true, schemaVersion: 1, generation,
    counts: { notes: notes.length, edges: allLinks().length, unresolvedLinks: unresolved(), skipped: lastSync ? skipped.length : 0 },
    ...(lastSync ? { lastSync: summaryOf(lastSync) } : {}), skipped: lastSync ? structuredClone(lastSync.skipped) : [],
    editing: { notes: true, memoryImport: true },
  });
  // A write the daemon makes re-indexes right away (an incremental sync), so the next status shows a new generation.
  const vault: MockVault = {
    notes: () => samples,
    put(sample) {
      const at = new Date().toISOString();
      const edited = { ...sample, ageMs: now - Date.now() };
      samples = samples.some(item => item.path === sample.path) ? samples.map(item => item.path === sample.path ? edited : item) : [...samples, edited];
      generation++;
      notes = index(samples, at, now);
      lastSync = report('incremental', at);
    },
  };
  const byId = (nodeId: unknown) => {
    const id = normalizeKnowledgeNodeId(nodeId);
    return notes.find(item => item.node.nodeId === id);
  };
  const page = (nodeId: string, links: KnowledgeLink[], cursor: unknown): KnowledgeLinkPage => {
    const from = normalizeKnowledgeCursor(cursor);
    const slice = links.slice(from, from + KNOWLEDGE_UI_LIMITS.linkPage);
    // The other endpoints on this page that are visible notes (targets, sources and candidates).
    const ids = new Set(slice.flatMap(link => [link.sourceNodeId, ...(link.targetNodeId ? [link.targetNodeId] : []), ...(link.candidates ?? [])]));
    ids.delete(nodeId);
    return {
      generation, nodeId, links: slice, nodes: notes.filter(item => ids.has(item.node.nodeId)).map(item => ref(item.node)),
      ...(from + slice.length < links.length ? { nextCursor: from + slice.length } : {}),
    };
  };

  return {
    ...createMockKnowledgeEdit(vault, latency, now, editOptions),
    async knowledgeStatus() { await latency(); return status(); },
    async syncKnowledge(syncMode) {
      const chosen = normalizeKnowledgeSyncMode(syncMode);
      await latency(); await latency();
      if (chosen === 'rebuild') generation++;
      notes = index(samples, new Date().toISOString(), now);
      lastSync = report(chosen, new Date().toISOString());
      return { report: structuredClone(lastSync), status: status() };
    },
    async knowledgeNode(lookup) {
      const target = normalizeKnowledgeNodeLookup(lookup);
      await latency();
      const found = 'nodeId' in target ? notes.find(item => item.node.nodeId === target.nodeId) : notes.find(item => item.node.path === target.path);
      return found ? { generation, node: structuredClone(found.node), body: found.body, bodyStatus: 'current', bodyTruncated: false } : null;
    },
    async knowledgeLinks(nodeId, cursor) {
      const found = byId(nodeId);
      await latency();
      return page(String(nodeId), found ? linksOf(found) : [], cursor);
    },
    async knowledgeBacklinks(nodeId, cursor) {
      const id = normalizeKnowledgeNodeId(nodeId);
      await latency();
      return page(id, allLinks().filter(link => link.status === 'resolved' && link.targetNodeId === id && link.sourceNodeId !== id), cursor);
    },
    async searchKnowledge(query) {
      const text = normalizeKnowledgeQuery(query);
      await latency();
      const terms = text.toLowerCase().split(/\s+/).slice(0, 16);
      const matches = notes.filter(item => {
        const haystack = [item.node.title, ...item.node.aliases, item.body].join('\n').toLowerCase();
        return terms.every(term => haystack.includes(term));
      });
      // Like FTS rank, roughly: title and alias matches first, then by path.
      const named = (item: Indexed) => [item.node.title, ...item.node.aliases].join('\n').toLowerCase();
      matches.sort((a, b) => Number(!terms.every(term => named(a).includes(term))) - Number(!terms.every(term => named(b).includes(term))) || a.node.path.localeCompare(b.node.path));
      const hits = matches.slice(0, KNOWLEDGE_UI_LIMITS.searchResults).map(item => {
        const text = snippet(item.body, terms);
        return { ...ref(item.node), ...(text ? { snippet: text } : {}) };
      });
      return { generation, hits };
    },
    async knowledgeOverview(options) {
      const { nodeLimit = KNOWLEDGE_OVERVIEW_LIMITS.nodes, edgeLimit = KNOWLEDGE_OVERVIEW_LIMITS.edges } = normalizeKnowledgeOverviewOptions(options);
      await latency();
      const unique = new Map<string, KnowledgeOverview['edges'][number]>();
      for (const link of allLinks()) {
        if (link.status !== 'resolved' || !link.targetNodeId || link.sourceNodeId === link.targetNodeId) continue;
        const edge = { source: link.sourceNodeId, target: link.targetNodeId, type: link.edgeType };
        unique.set(JSON.stringify([edge.source, edge.target, edge.type]), edge);
      }
      const edges = [...unique.values()];
      const incoming = new Map<string, number>(), outgoing = new Map<string, number>();
      for (const edge of edges) {
        incoming.set(edge.target, (incoming.get(edge.target) ?? 0) + 1);
        outgoing.set(edge.source, (outgoing.get(edge.source) ?? 0) + 1);
      }
      const nodes = notes.map(({ node }) => {
        const inDegree = incoming.get(node.nodeId) ?? 0, outDegree = outgoing.get(node.nodeId) ?? 0;
        return { ...ref(node), kind: node.kind, folder: folderOf(node.path), tags: [...node.tags],
          degree: inDegree + outDegree, inDegree, outDegree, modifiedAt: node.sourceModifiedAt };
      });
      const compare = (a: string, b: string) => a < b ? -1 : a > b ? 1 : 0;
      nodes.sort((a, b) => b.degree - a.degree || compare(a.nodeId, b.nodeId));
      const kept = new Map(nodes.slice(0, nodeLimit).map(node => [node.nodeId, node]));
      const weight = (edge: KnowledgeOverview['edges'][number]) => kept.get(edge.source)!.degree + kept.get(edge.target)!.degree;
      const selected = edges.filter(edge => kept.has(edge.source) && kept.has(edge.target));
      selected.sort((a, b) => weight(b) - weight(a) || compare(a.source, b.source) || compare(a.target, b.target) || compare(a.type, b.type));
      const bounded = selected.slice(0, edgeLimit);
      return { generation, totalNodes: nodes.length, totalEdges: edges.length,
        truncated: kept.size < nodes.length || bounded.length < edges.length, nodes: [...kept.values()], edges: bounded };
    },
    async knowledgeGraph(nodeId, depth) {
      const root = byId(nodeId);
      const hops = normalizeKnowledgeGraphDepth(depth);
      await latency();
      const graph: KnowledgeGraph = { generation, rootNodeId: String(nodeId), depth: hops, nodes: [], edges: [], truncated: false };
      if (!root) return graph;
      const resolved = allLinks().flatMap(link => link.status === 'resolved' && link.targetNodeId ? [{ source: link.sourceNodeId, target: link.targetNodeId, edgeType: link.edgeType }] : []);
      const seen = new Map<string, number>([[root.node.nodeId, 0]]);
      const queue = [root.node.nodeId];
      while (queue.length) {
        const current = queue.shift()!;
        const distance = seen.get(current)!;
        if (distance >= hops) continue;
        for (const edge of resolved) {
          const next = edge.source === current ? edge.target : edge.target === current ? edge.source : undefined;
          if (!next || seen.has(next)) continue;
          if (seen.size >= KNOWLEDGE_UI_LIMITS.graphNodes) { graph.truncated = true; break; }
          seen.set(next, distance + 1);
          queue.push(next);
        }
      }
      graph.nodes = notes.filter(item => seen.has(item.node.nodeId)).map(item => ({ nodeId: item.node.nodeId, title: item.node.title }));
      const unique = new Set<string>();
      graph.edges = resolved.filter(edge => seen.has(edge.source) && seen.has(edge.target) && edge.source !== edge.target).filter(edge => {
        const key = `${edge.source}\n${edge.edgeType}\n${edge.target}`;
        if (unique.has(key)) return false;
        unique.add(key);
        return true;
      });
      return graph;
    },
  };
}
