const EDGE_LABELS: [RegExp, KnowledgeEdgeType][] = [
  [/^\s*related:/i, 'related_to'], [/^\s*learned from:/i, 'learned_from'], [/^\s*depends on:/i, 'depends_on'], [/^\s*supersedes:/i, 'supersedes'], [/^\s*used by:/i, 'used_by'],
];

interface Indexed { node: KnowledgeNode & { sourceModifiedAt: string }; body: string; key: string; stem: string; aliasKeys: string[] }
interface RawLink { target: string; heading?: string; display?: string; embed: boolean; line: number; edgeType: KnowledgeEdgeType }
type Resolved = Pick<KnowledgeLink, 'status' | 'via' | 'targetNodeId' | 'candidates'>;

const stripMd = (path: string) => path.replace(/\.md$/i, '');
const stemOf = (path: string) => stripMd(path).split('/').pop()!;
const folderOf = (path: string) => path.includes('/') ? path.slice(0, path.lastIndexOf('/')) : '';
const ref = (node: KnowledgeNode): KnowledgeNodeRef => ({ nodeId: node.nodeId, path: node.path, title: node.title });

/** Wikilinks outside fenced code and inline code spans, with their line and edge type. */
function extractLinks(body: string, firstLine: number): RawLink[] {
  const links: RawLink[] = [];
  let fenced = false;
  body.split('\n').forEach((line, index) => {
    if (/^ {0,3}(`{3,}|~{3,})/.test(line)) { fenced = !fenced; return; }
    if (fenced) return;
    const edgeType = EDGE_LABELS.find(([pattern]) => pattern.test(line))?.[1] ?? 'links_to';
    const text = line.replace(/`[^`]*`/g, match => ' '.repeat(match.length));
    for (const match of text.matchAll(/(\\?)(!?)\[\[((?:[^[\]\n\\]|\\.)+?)\]\]/g)) {
      if (match[1]) continue;
      const link = parseWikilink(match[3]!, match[2] === '!');
      if (link) links.push({ target: link.target, embed: link.embed, line: firstLine + index, edgeType, ...(link.heading ? { heading: link.heading } : {}), ...(link.display ? { display: link.display } : {}) });
    }
  });
  return links;
}

function hex(seed: string): string {
  let state = 2166136261;
  for (const character of seed) state = Math.imul(state ^ character.charCodeAt(0), 16777619) >>> 0;
  let out = '';
  while (out.length < 64) { state = (Math.imul(state, 1664525) + 1013904223) >>> 0; out += state.toString(16).padStart(8, '0'); }
  return out.slice(0, 64);
}

function index(samples: readonly SampleNote[], observedAt: string, now: number): Indexed[] {
  return samples.map((sample, position) => {
    const title = /^# (.+)$/m.exec(sample.body)?.[1]?.trim() ?? stemOf(sample.path);
    const node: Indexed['node'] = {
      nodeId: sample.id ?? `path:${sample.path}`, idFromFrontMatter: Boolean(sample.id), path: sample.path, kind: sample.kind ?? 'note', title,
      aliases: sample.aliases ?? [], tags: sample.tags ?? [], origin: 'vault', trustStatus: 'untrusted', sourceSha256: hex(sample.path + sample.body),
      sourceModifiedAt: new Date(now - (sample.ageMs ?? (position + 1) * 3_600_000 * 7)).toISOString(), observedAt,
      ...(sample.verification ? { declaredVerification: sample.verification } : {}), ...(sample.revision ? { declaredRevision: sample.revision } : {}),
      declaredSourceTaskIds: sample.sourceTaskIds ?? [],
    };
    return { node, body: sample.body, key: stripMd(sample.path).toLowerCase(), stem: stemOf(sample.path).toLowerCase(), aliasKeys: node.aliases.map(alias => alias.toLowerCase()) };
  });
}

/** Normalize like the core: `./`, `../` and `/` are vault paths relative to the source (path-only); `.md` is dropped. */
function normalizeTarget(sourcePath: string, raw: string): { key: string; written: string; pathOnly: boolean } {
  const pathOnly = /^(\.{1,2}\/|\/)/.test(raw);
  const base = raw.startsWith('/') ? [] : pathOnly ? folderOf(sourcePath).split('/').filter(Boolean) : [];
  for (const segment of stripMd(raw).split('/')) {
    if (!segment || segment === '.') continue;
    if (segment === '..') base.pop(); else base.push(segment);
  }
  const written = base.join('/');
  return { key: written.toLowerCase(), written, pathOnly };
}

type Tier = [KnowledgeResolution, (item: Indexed) => boolean, (item: Indexed) => boolean];

function resolve(notes: readonly Indexed[], sourcePath: string, raw: string): Resolved {
  const { key, written, pathOnly } = normalizeTarget(sourcePath, raw);
  const tiers: Tier[] = [
    ['path', item => item.key === key, item => stripMd(item.node.path) === written],
    ...(pathOnly ? [] : [
      ['path_suffix', item => key.includes('/') && item.key.endsWith(`/${key}`), item => stripMd(item.node.path).endsWith(`/${written}`)],
      ['title', item => item.stem === key, item => stemOf(item.node.path) === written],
      ['alias', item => item.aliasKeys.includes(key), item => item.node.aliases.includes(written)],
    ] satisfies Tier[]),
  ];
  for (const [via, matches, exactCase] of tiers) {
    const candidates = notes.filter(matches);
    if (!candidates.length) continue;
    const chosen = candidates.length === 1 ? candidates : candidates.filter(exactCase);
    if (chosen.length === 1) return { status: 'resolved', via, targetNodeId: chosen[0]!.node.nodeId };
    return { status: 'ambiguous', candidates: candidates.sort((a, b) => a.node.path.localeCompare(b.node.path)).slice(0, 16).map(item => item.node.nodeId) };
  }
  return { status: 'missing' };
}

/** Plain text around the first match, without Markdown punctuation. */
function snippet(body: string, terms: readonly string[]): string | undefined {
  const plain = body.replace(/^# .*$/m, ' ').replace(/```[\s\S]*?```/g, ' ').replace(/^[\s|:-]*-{3,}[\s|:-]*$/gm, ' ').replace(/!?\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\|([^\]]+))?\]\]/g, (_m, target: string, display?: string) => display ?? target)
    .replace(/[#*_`>|]/g, ' ').replace(/\s+/g, ' ').trim();
  const lower = plain.toLowerCase();
  const at = Math.min(...terms.map(term => lower.indexOf(term)).filter(position => position >= 0));
  if (!Number.isFinite(at)) return plain.slice(0, 140) || undefined;
  const start = Math.max(0, at - 50);
  return `${start ? '…' : ''}${plain.slice(start, start + 140).trim()}${start + 140 < plain.length ? '…' : ''}`;
}

